using System.Text.Json;
using System.Text.Json.Serialization;
using PortAtlas.Core.Export;

namespace PortAtlas.Cli.Configuration;

/// <summary>
/// Generates standard baseline JSON configuration templates for PortAtlas.
/// </summary>
public static class ConfigurationTemplateGenerator
{
    private static readonly JsonSerializerOptions JsonOptions = new()
    {
        WriteIndented = true,
        DefaultIgnoreCondition = JsonIgnoreCondition.Never
    };

    /// <summary>
    /// Generates a standard baseline configuration file at the specified target path.
    /// </summary>
    /// <param name="targetPath">Target file path or directory (defaults to 'portatlas.json' in current directory).</param>
    /// <returns>Resolved absolute path of the generated configuration file.</returns>
    public static string GenerateDefaultConfigFile(string? targetPath = null)
    {
        var resolvedPath = ResolveTargetPath(targetPath);

        // The template holds the built-in defaults, so that a file generated by "config init" behaves exactly like
        // running without a file; only the column list is spelled out, as a starting point for editing it.
        var defaultConfig = new AppConfiguration
        {
            CsvColumns = [.. AuditCsvColumnCatalog.GetAllDescriptors().Select(d => d.Name)]
        };

        var json = JsonSerializer.Serialize(defaultConfig, JsonOptions);
        var dir = Path.GetDirectoryName(resolvedPath);
        if (!string.IsNullOrEmpty(dir) && !Directory.Exists(dir))
        {
            Directory.CreateDirectory(dir);
        }

        File.WriteAllText(resolvedPath, json);
        return resolvedPath;
    }

    private static string ResolveTargetPath(string? targetPath)
    {
        if (string.IsNullOrWhiteSpace(targetPath))
        {
            return Path.GetFullPath("portatlas.json");
        }

        var trimmed = targetPath.Trim();
        if (Directory.Exists(trimmed) || trimmed.EndsWith(Path.DirectorySeparatorChar) || trimmed.EndsWith(Path.AltDirectorySeparatorChar))
        {
            return Path.GetFullPath(Path.Combine(trimmed, "portatlas.json"));
        }

        return Path.GetFullPath(trimmed);
    }
}
